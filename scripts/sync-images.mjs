// ─────────────────────────────────────────────────────────────────────────────
//  Image sync — run automatically before `npm start` and `npm run build`
//  (or by hand: `npm run images`).
//
//  1. Makes sure every category has a folder under public/images/products/.
//  2. Looks for a photo for every product, named after the product's slug:
//        public/images/products/<category-id>/<product-slug>.jpg  (.jpeg .png .webp also work)
//     and a cover photo for every category:
//        public/images/categories/<category-id>.jpg
//  3. Writes src/app/data/product-images.generated.ts with only the files that
//     really exist. Products with no local photo keep their current photo
//     (or the category icon if they have none).
//  4. Writes public/images/IMAGE-FILENAMES.md — the exact file names to use,
//     with ✅ / ⬜ showing which ones you have already added.
// ─────────────────────────────────────────────────────────────────────────────
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const productsTs = path.join(root, 'src/app/data/products.ts');
const imagesDir = path.join(root, 'public/images');
const productsDir = path.join(imagesDir, 'products');
const coversDir = path.join(imagesDir, 'categories');
const outTs = path.join(root, 'src/app/data/product-images.generated.ts');
const outMd = path.join(imagesDir, 'IMAGE-FILENAMES.md');
const EXT = ['.jpg', '.jpeg', '.png', '.webp'];

// Load the catalog straight from products.ts (transpiled in memory, generated map stubbed out).
const src = fs
  .readFileSync(productsTs, 'utf8')
  .replace(/^import .*product-images\.generated.*$/m, 'const LOCAL_IMAGES = {}, CATEGORY_COVERS = {};');
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
const { CATEGORIES } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));

const find = (dir, base) => {
  for (const ext of EXT) {
    for (const name of [base + ext, base + ext.toUpperCase()]) {
      if (fs.existsSync(path.join(dir, name))) return name;
    }
  }
  return undefined;
};

fs.mkdirSync(coversDir, { recursive: true });
const local = {};
const covers = {};
const md = [
  '# Product image file names',
  '',
  '_Generated by `scripts/sync-images.mjs` — do not edit by hand. Re-run `npm run images` after adding photos._',
  '',
  'Drop each photo into its category folder using the exact file name below. `.jpg`, `.jpeg`, `.png` and `.webp` all work',
  '(the list shows `.jpg`). Square photos on a white background look best, about 800 × 800 px.',
  'If a file is missing, the website keeps using the current photo, or the category icon.',
  '',
  '✅ = your photo is in place · ⬜ = not added yet (current photo is used)',
  '',
];
let found = 0;
let total = 0;

for (const c of CATEGORIES) {
  const dir = path.join(productsDir, c.id);
  fs.mkdirSync(dir, { recursive: true });
  const cover = find(coversDir, c.id);
  if (cover) covers[c.id] = `images/categories/${cover}`;

  md.push(`## ${c.name}`, '', `Folder: \`public/images/products/${c.id}/\``, '');
  md.push(`Category cover (optional): ${cover ? '✅' : '⬜'} \`public/images/categories/${cover ?? c.id + '.jpg'}\``, '');
  md.push('| | File name | Product | Size |', '|---|---|---|---|');
  for (const p of c.products) {
    total++;
    const file = find(dir, p.slug);
    if (file) {
      local[p.id] = `images/products/${c.id}/${file}`;
      found++;
    }
    md.push(`| ${file ? '✅' : '⬜'} | \`${file ?? p.slug + '.jpg'}\` | ${p.name} | ${p.size ?? ''} |`);
  }
  md.push('');
}

const dupes = CATEGORIES.flatMap((c) => c.products.map((p) => `${c.id}/${p.slug}`)).filter((s, i, a) => a.indexOf(s) !== i);
if (dupes.length) console.warn('⚠ Two products share a file name — give one a different size or name:', [...new Set(dupes)]);

const body = (o) => Object.entries(o).map(([k, v]) => `  '${k}': '${v}',`).join('\n');
fs.writeFileSync(
  outTs,
  `// AUTO-GENERATED by scripts/sync-images.mjs — do not edit. Run \`npm run images\` to refresh.\n` +
    `// Only photos that exist in public/images are listed; everything else falls back to the current photo.\n\n` +
    `/** Product id → local photo path. */\nexport const LOCAL_IMAGES: Record<string, string> = {\n${body(local)}\n};\n\n` +
    `/** Category id → local cover photo path. */\nexport const CATEGORY_COVERS: Record<string, string> = {\n${body(covers)}\n};\n`,
);
fs.writeFileSync(outMd, md.join('\n'));
console.log(`Images: ${found}/${total} products have a local photo, ${Object.keys(covers).length}/${CATEGORIES.length} category covers.`);
